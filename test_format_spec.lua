local DIR = debug.getinfo(1, "S").source:sub(2):match("(.*[/\\])") or "./"
local Format = dofile(DIR .. "calc_format.lua")
local NN = "\u{202F}"

describe("calc_format", function()
    it("follows the language's decimal separator", function()
        assert.are.equal(",", Format.decimalSep("fr"))
        assert.are.equal(".", Format.decimalSep("en"))
        assert.are.equal(",", Format.decimalSep("de"))
        assert.are.equal(".", Format.decimalSep("ja"))
    end)

    it("groups thousands", function()
        assert.are.equal("1" .. NN .. "234" .. NN .. "567,5", Format.number(1234567.5, "fr"))
        assert.are.equal("1,234,567.5", Format.number(1234567.5, "en"))
        assert.are.equal("1.234,5", Format.number(1234.5, "de"))
        assert.are.equal("999", Format.number(999, "en"))
        assert.are.equal("−1,000", Format.number(-1000, "en"))
    end)

    it("shows 12 significant digits and drops trailing zeros", function()
        assert.are.equal("0.3", Format.number(0.1 + 0.2, "en"))
        assert.are.equal("0.333333333333", Format.number(1 / 3, "en"))
        assert.are.equal("0.666666666667", Format.number(2 / 3, "en"))
        assert.are.equal("2", Format.number(2.0, "en"))
        assert.are.equal("0,5", Format.number(0.5, "fr"))
        assert.are.equal("0", Format.number(-0.0, "en"))
        assert.are.equal("123,456,789,012,345", Format.number(123456789012345, "en"))
    end)

    it("switches to scientific notation for very large and small values", function()
        assert.are.equal("1.5 × 10¹⁸", Format.number(1.5e18, "en"))
        assert.are.equal("1,5 × 10¹⁸", Format.number(1.5e18, "fr"))
        assert.are.equal("1.23456789 × 10⁻⁷", Format.number(1.23456789e-7, "en"))
        assert.are.equal("−2 × 10²⁰", Format.number(-2e20, "en"))
        assert.are.equal("1 × 10¹⁵", Format.number(1e15, "en"))
    end)

    it("caps decimals when asked", function()
        assert.are.equal("33.33", Format.number(100 / 3, "en", 2))
        assert.are.equal("12,5", Format.number(12.5, "fr", 2))
        assert.are.equal("0", Format.number(0.0001, "en", 2))
    end)

    it("formats money with two decimals", function()
        assert.are.equal("1" .. NN .. "109,20", Format.money(1109.2, "fr"))
        assert.are.equal("1,109.20", Format.money(1109.1951, "en"))
        assert.are.equal("0.00", Format.money(-0.001, "en"))
    end)

    it("localises typed numbers as they are typed", function()
        assert.are.equal("12,", Format.localise("12.", "fr"))
        assert.are.equal("1" .. NN .. "234,05", Format.localise("1234.05", "fr"))
        assert.are.equal("0.", Format.localise("0.", "en"))
    end)

    it("keeps full precision in pasted values", function()
        assert.are.equal(1 / 3, tonumber(Format.valueToken(1 / 3):sub(3)))
        assert.are.equal("v:-5", Format.valueToken(-5))
        assert.are.equal("v:0", Format.valueToken(-0.0))
    end)

    it("writes the expression line", function()
        assert.are.equal("12 + 3,5 × (2 − 1)",
            Format.expression({ "12", "+", "3.5", "*", "(", "2", "-", "1", ")" }, "fr"))
        assert.are.equal("−2 × −3", Format.expression({ "-", "2", "*", "-", "3" }, "en"))
        assert.are.equal("√(2)²", Format.expression({ "sqrt(", "2", ")", "sq" }, "en"))
        assert.are.equal("2π ÷ 3!", Format.expression({ "2", "pi", "/", "3", "!" }, "en"))
        assert.are.equal("−7 + 10%", Format.expression({ "neg", "7", "+", "10", "%" }, "en"))
        assert.are.equal("0.5⁻¹", Format.expression({ "v:0.5", "inv" }, "en"))
    end)
end)
