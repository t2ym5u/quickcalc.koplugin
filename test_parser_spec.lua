local DIR = debug.getinfo(1, "S").source:sub(2):match("(.*[/\\])") or "./"
local Parser = dofile(DIR .. "calc_parser.lua")

local function ev(s, angle)
    local t = assert(Parser.tokenize(s), "tokenize " .. s)
    return Parser.evaluate(t, { angle = angle })
end

local function near(a, b) return math.abs(a - b) < 1e-9 * math.max(1, math.abs(b)) end

describe("calc_parser", function()
    it("respects operator precedence", function()
        assert.are.equal(14, ev("2+3*4"))
        assert.are.equal(20, ev("(2+3)*4"))
        assert.are.equal(2, ev("8/2/2"))
        assert.are.equal(5, ev("10-3-2"))
    end)

    it("makes ^ right-associative and tighter than the sign", function()
        assert.are.equal(512, ev("2^3^2"))
        assert.are.equal(-4, ev("-2^2"))
        assert.are.equal(0.5, ev("2^-1"))
        assert.are.equal(4, ev("(-2)^2"))
    end)

    it("handles unary minus and the neg token", function()
        assert.are.equal(-6, ev("2*-3"))
        assert.are.equal(5, ev("--5"))
        assert.are.equal(-7, Parser.evaluate({ "neg", "7" }))
        assert.are.equal(-1, Parser.evaluate({ "2", "-", "3" }))
    end)

    it("applies the pocket-calculator percent rule", function()
        assert.are.equal(220, ev("200+10%"))
        assert.are.equal(180, ev("200-10%"))
        assert.are.equal(20, ev("200*10%"))
        assert.are.equal(0.5, ev("50%"))
        assert.are.equal(2000, ev("200/10%"))
    end)

    it("reads implicit multiplication", function()
        assert.is_true(near(ev("2pi"), 2 * math.pi))
        assert.are.equal(15, ev("3(4+1)"))
        assert.are.equal(6, ev("(1+1)(1+2)"))
    end)

    it("closes missing parentheses", function()
        assert.are.equal(9, ev("(1+2)*(1+2"))
        assert.are.equal(3, ev("sqrt(9"))
    end)

    it("computes the postfix operators", function()
        assert.are.equal(120, ev("5!"))
        assert.are.equal(1, ev("0!"))
        assert.are.equal(9, Parser.evaluate({ "3", "sq" }))
        assert.are.equal(27, Parser.evaluate({ "3", "cube" }))
        assert.are.equal(0.25, Parser.evaluate({ "4", "inv" }))
        assert.are.equal(-8, Parser.evaluate({ "neg", "2", "cube" }))
    end)

    it("evaluates functions in degrees exactly where it matters", function()
        assert.are.equal(0, ev("sin(180)", "deg"))
        assert.are.equal(0, ev("cos(90)", "deg"))
        assert.are.equal(0, ev("cos(270)", "deg"))
        assert.are.equal(1, ev("sin(90)", "deg"))
        assert.is_true(near(ev("sin(30)", "deg"), 0.5))
        assert.is_true(near(ev("tan(45)", "deg"), 1))
        assert.are.equal(0, ev("sin(-360)", "deg"))
    end)

    it("evaluates functions in radians", function()
        assert.are.equal(0, ev("sin(pi)", "rad"))
        assert.is_true(near(ev("cos(pi)", "rad"), -1))
        assert.is_true(near(ev("sin(pi/2)", "rad"), 1))
    end)

    it("computes log, ln, roots", function()
        assert.are.equal(3, ev("log(1000)"))
        assert.are.equal(-2, ev("log(0.01)"))
        assert.is_true(near(ev("ln(e)"), 1))
        assert.are.equal(3, Parser.evaluate({ "cbrt(", "27", ")" }))
        assert.are.equal(-2, Parser.evaluate({ "cbrt(", "neg", "8", ")" }))
        assert.are.equal(12, ev("sqrt(144)"))
    end)

    it("cleans the round-off of sums", function()
        assert.are.equal(0, ev("0.3-0.1-0.2"))
        assert.are.equal(0, ev("1-0.9-0.1"))
    end)

    it("reports division by zero", function()
        local v, err = ev("5/0")
        assert.is_nil(v); assert.are.equal("div0", err)
        assert.are.equal("div0", select(2, Parser.evaluate({ "0", "inv" })))
        assert.are.equal("div0", select(2, ev("0^-1")))
        assert.are.equal("div0", select(2, ev("5/(2-2)")))
    end)

    it("reports domain errors", function()
        assert.are.equal("domain", select(2, ev("sqrt(-1)")))
        assert.are.equal("domain", select(2, ev("ln(0)")))
        assert.are.equal("domain", select(2, ev("log(-5)")))
        assert.are.equal("domain", select(2, ev("2.5!")))
        assert.are.equal("domain", select(2, ev("(-3)!")))
        assert.are.equal("domain", select(2, ev("tan(90)", "deg")))
        assert.are.equal("domain", select(2, ev("tan(-270)", "deg")))
        assert.are.equal("domain", select(2, ev("(-8)^0.5")))
    end)

    it("reports overflow", function()
        assert.are.equal("overflow", select(2, ev("10^100")))
        assert.are.equal("overflow", select(2, ev("70!")))
        assert.are.equal("overflow", select(2, ev("171!")))
        assert.is_true(ev("69!") > 1e98)
        assert.are.equal("overflow", select(2, ev("10^50*10^50")))
    end)

    it("reports syntax errors instead of throwing", function()
        assert.are.equal("syntax", select(2, ev("2+")))
        assert.are.equal("syntax", select(2, ev("*2")))
        assert.are.equal("syntax", select(2, ev("()")))
        assert.are.equal("syntax", select(2, ev("2)")))
        assert.are.equal("syntax", select(2, Parser.evaluate({})))
        assert.are.equal("syntax", select(2, Parser.evaluate({ "." })))
        assert.are.equal("syntax", select(2, Parser.evaluate({ "os.exit(", ")" })))
    end)

    it("reads pasted values", function()
        assert.are.equal(-5, Parser.evaluate({ "v:-5" }))
        assert.are.equal(1.5e20, Parser.evaluate({ "v:1.5e+20" }))
        assert.are.equal(10, Parser.evaluate({ "v:-5", "*", "neg", "2" }))
    end)

    it("never runs Lua code", function()
        assert.is_nil(Parser.tokenize("os.exit()"))
        assert.is_nil(Parser.tokenize("2;print(1)"))
    end)

    it("never returns -0", function()
        local v = ev("0*-1")
        assert.are.equal("0", string.format("%g", v))
    end)
end)
